# This file demonstrates numbers, arithmetic, comparisons, and logic.

a = 17
b = 5

# Basic arithmetic operations.
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Modulo:", a % b)

# Comparison operators.
print("a > b:", a > b)
print("a == b:", a == b)
print("a != b:", a != b)

# Logical operators.
print("AND:", a > 10 and b < 10)
print("OR:", a < 10 or b < 10)
print("NOT:", not (a == b))

# / returns a floating-point result, while // returns
# the floor of the division result.