# This file demonstrates basic Python variable types.

name = "Maria"
age = 22
height = 168.0
is_student = True
nothing = None

# Print each value together with its type.
print(name, type(name))
print(age, type(age))
print(height, type(height))
print(is_student, type(is_student))
print(nothing, type(nothing))

# A variable can be reassigned to a value of a different type.
age = "twenty-two"
print(age, type(age))